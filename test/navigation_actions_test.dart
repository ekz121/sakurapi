import 'package:flutter_test/flutter_test.dart';
import 'package:intl/date_symbol_data_local.dart';
import 'package:material_ui/material_ui.dart';
import 'package:sqflite_common_ffi/sqflite_ffi.dart';
import 'package:sakurapi/app_store.dart';
import 'package:sakurapi/data/finance_repository.dart';
import 'package:sakurapi/domain/formatters.dart';
import 'package:sakurapi/main.dart';

void main() {
  testWidgets('balance visibility, opening balance, shortcuts, filters, category CRUD', (tester) async {
    tester.view.physicalSize = const Size(430, 932);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    await initializeDateFormatting('id_ID');
    sqfliteFfiInit();
    final repo = FinanceRepository(factory: databaseFactoryFfiNoIsolate, databasePath: inMemoryDatabasePath);
    final store = AppStore(repo);
    await tester.runAsync(store.refresh);
    await tester.pumpWidget(SakuRapiApp(store: store));
    Future<void> settleDatabase() async {
      await tester.runAsync(() => Future<void>.delayed(const Duration(milliseconds: 100)));
      await tester.pumpAndSettle();
    }
    await settleDatabase();
    await tester.tap(find.byTooltip('Sembunyikan saldo'));
    await tester.pumpAndSettle();
    expect(find.text('Saldo disembunyikan'), findsOneWidget);
    await tester.tap(find.byTooltip('Tampilkan saldo'));
    await tester.pumpAndSettle();
    await tester.tap(find.byTooltip('Ubah saldo awal'));
    await tester.pumpAndSettle();
    await tester.enterText(find.byType(TextFormField), '1..000');
    await tester.tap(find.text('Simpan'));
    await tester.pumpAndSettle();
    expect(find.text('Masukkan bilangan rupiah yang valid'), findsOneWidget);
    await tester.enterText(find.byType(TextFormField), '500000');
    await tester.tap(find.text('Simpan'));
    await settleDatabase();
    expect(store.balance, 500000);
    await tester.tap(find.text('Laporan').first);
    await tester.pumpAndSettle();
    await tester.tap(find.byTooltip('Bulan sebelumnya'));
    await tester.pumpAndSettle();
    await tester.tap(find.byTooltip('Bulan berikutnya'));
    await tester.pumpAndSettle();
    await tester.tap(find.text(monthLabel(DateTime.now())).first);
    await tester.pumpAndSettle();
    expect(find.text('Pilih bulan laporan'), findsOneWidget);
    await tester.tap(find.text('Batal'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('Kategori').last);
    await tester.pumpAndSettle();
    await tester.tap(find.text('Kategori baru'));
    await tester.pumpAndSettle();
    await tester.enterText(find.byType(TextFormField), 'Kategori uji');
    await tester.tap(find.byTooltip('Warna kategori 2'));
    await tester.tap(find.byTooltip('food'));
    await tester.ensureVisible(find.text('Simpan kategori'));
    await tester.tap(find.text('Simpan kategori'));
    await settleDatabase();
    expect(store.categories.any((c) => c.name == 'Kategori uji'), isTrue);
    await tester.ensureVisible(find.text('Kategori uji'));
    await tester.tap(find.text('Kategori uji'));
    await tester.pumpAndSettle();
    await tester.enterText(find.byType(TextFormField), 'Kategori diubah');
    await tester.ensureVisible(find.text('Simpan kategori'));
    await tester.tap(find.text('Simpan kategori'));
    await settleDatabase();
    await tester.ensureVisible(find.text('Kategori diubah'));
    final row = find.ancestor(of: find.text('Kategori diubah'), matching: find.byType(ListTile)).first;
    await tester.tap(find.descendant(of: row, matching: find.byTooltip('Opsi kategori')));
    await tester.pumpAndSettle();
    await tester.tap(find.text('Hapus').last);
    await tester.pumpAndSettle();
    await tester.tap(find.text('Hapus').last);
    await settleDatabase();
    expect(store.categories.any((c) => c.name == 'Kategori diubah'), isFalse);
    await tester.tap(find.text('Transaksi').last);
    await tester.pumpAndSettle();
    await tester.enterText(find.byType(TextField).first, 'tidak ada');
    await tester.tap(find.text('Pemasukan').first);
    await tester.pumpAndSettle();
    expect(find.text('Tidak ada transaksi'), findsOneWidget);
    await tester.tap(find.byType(SwitchListTile));
    await tester.pumpAndSettle();
    expect(find.byTooltip('Bulan sebelumnya'), findsWidgets);
    await tester.tap(find.text('Ringkasan').last);
    await tester.pumpAndSettle();
    await tester.ensureVisible(find.text('Scan struk'));
    await tester.tap(find.text('Scan struk'));
    await tester.pumpAndSettle();
    expect(find.text('Ambil foto struk'), findsOneWidget);
    expect(find.text('Pilih dari galeri'), findsOneWidget);
    expect(tester.takeException(), isNull);
    await tester.pumpWidget(const SizedBox.shrink());
    store.dispose();
    await repo.close();
  });
}
